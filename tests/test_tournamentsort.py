
def tournament_sort(arr): # defined an sorting function that asks a list as parameter (unsorted strings, generated by the database)

    if len(arr) <= 1: # if there's only 1 or less statments
        return arr.copy() # returns a copy of the list

    elements = arr.copy() # makes a copy of the list to preserve the original
    n = len(elements) # gets the number of elements from the lists copy

    index = 1 # it starts from the first term

    while index < n: # while the index is less than the total amount of items
        index *= 2 # multiplies the index number by 2

    tree = [None] * (2 * index) #creates a tree, the stored value is the double of the index

    for i in range(n): # the sorting algorithm repeats for each item in the list
        tree[index + i] = i # after every repetition updates the trees index value

    def winner(a, b): # the function takes 2 statments to return a winner

        if a is None: # if there isn't an "a"
            return b # returns "b"

        if b is None: # if there isn't an "b"
            return a # returns "a"

        if elements[a] <= elements[b]: # if the "a" is smaller than "b" 
            return a # returns "a"

        return b # else returns "b"

    for i in range(index - 1, 0, -1):
        tree[i] = winner(
            tree[2 * i],
            tree[2 * i + 1]
        )

    results = []

    for _ in range(n): # repeats with the lists numbers

        indicator = tree[1] # stores the first of the trees itens

        results.append(elements[indicator])

        position = index + indicator

        tree[position] = None

        position //=2

        while position >= 1:

            tree[position] = winner(
                tree[2 * position],
                tree[2 * position + 1]
            )

            position //=2

    return results

print(tournament_sort())
